import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { pages } from '../catalog.mjs';

const site = fileURLToPath(new URL('../', import.meta.url));
const root = path.dirname(site.replace(/\/$/, ''));
const github = 'https://github.com/MikeK184/Recollect/blob/main/';
const published = new Map(pages.map(page => [page.source, `/docs/${page.slug}.md`]));
const tracked = new Set(execFileSync('git', ['ls-files', '-z'], { cwd: root }).toString().split('\0'));

for (const directory of ['content', 'public']) {
  const target = path.join(site, directory);
  try {
    await readFile(path.join(target, '.generated-by-recollect'));
  } catch {
    try {
      if ((await readdir(target)).length) throw new Error(`Refusing to replace unowned ${target}`);
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  await rm(target, { recursive: true, force: true });
  await mkdir(target, { recursive: true });
  await writeFile(path.join(target, '.generated-by-recollect'), 'Generated by site/scripts/prepare.mjs\n');
}
await cp(path.join(site, 'pages'), path.join(site, 'content'), { recursive: true });

for (const page of pages) {
  const input = await readFile(path.join(root, page.source), 'utf8');
  let fenced = false;
  let fence = '';
  const output = input.split('\n').map(line => {
    const marker = line.match(/^\s*(`{3,}|~{3,})/);
    if (marker) {
      if (!fenced) { fenced = true; fence = marker[1][0]; }
      else if (marker[1][0] === fence) fenced = false;
      return line;
    }
    if (fenced) return line;
    return line.replace(/(!?\[[^\]]*\])\(([^\s)]+)\)/g, (match, label, target) => {
      if (/^(https?:|mailto:|#)/.test(target)) return match;
      const [filename, fragment] = target.split('#');
      const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(page.source), filename));
      const anchor = fragment ? `#${fragment}` : '';
      if (published.has(resolved)) return `${label}(${published.get(resolved)}${anchor})`;
      if (tracked.has(resolved)) return `${label}(${github}${resolved}${anchor})`;
      return `${label.replace(/^!?\[|\]$/g, '')} (local file: \`${target}\`)`;
    });
  }).join('\n');
  await writeFile(path.join(site, 'content/docs', `${page.slug}.md`), `---\ntitle: ${JSON.stringify(page.title)}\nsource: ${JSON.stringify(page.source)}\n---\n\n${output}`);
}

await mkdir(path.join(site, 'public/brand'));
for (const name of ['recollect-logo.svg', 'recollect-symbol.svg']) {
  await cp(path.join(root, 'web/public/brand', name), path.join(site, 'public/brand', name));
}
await mkdir(path.join(site, 'public/fonts'));
for (const name of ['newsreader-variable.ttf', 'manrope-variable.ttf', 'dm-mono-regular.ttf']) {
  await cp(path.join(root, 'web/public/fonts', name), path.join(site, 'public/fonts', name));
}
await mkdir(path.join(site, 'public/licenses'));
for (const name of ['newsreader-OFL.txt', 'manrope-OFL.txt', 'dmmono-OFL.txt']) {
  await cp(path.join(root, 'web/public/licenses', name), path.join(site, 'public/licenses', name));
}
await mkdir(path.join(site, 'public/visuals'));
for (const name of ['agent-workflow', 'environment-access', 'private-runner']) {
  await cp(path.join(root, 'docs/assets', `recollect-${name}-v3.png`), path.join(site, 'public/visuals', `recollect-${name}-v3.png`));
}
await writeFile(path.join(site, 'public/.nojekyll'), '');
console.log(`Prepared ${pages.length} canonical guides and 2 website pages.`);
